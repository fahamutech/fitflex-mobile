class FFLocaleScope extends InheritedNotifier<FFLocale> {
  const FFLocaleScope({
    super.key,
    required FFLocale notifier,
    required super.child,
  }) : super(notifier: notifier);

  static FFLocale of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<FFLocaleScope>();
    assert(scope != null, 'FFLocaleScope missing in widget tree');
    return scope!.notifier!;
  }
}

extension TString on BuildContext {
  String tr(String key) => FFLocaleScope.of(this).t(key);
}
